import { createClient } from "@/lib/supabase/server";
import { NextRequest, NextResponse } from "next/server";
import { z } from "zod";

interface Params {
  params: Promise<{ id: string }>;
}

const guestSchema = z.object({
  name: z.string().min(1).max(200),
  phone: z.string().max(40).optional(),
});
const bodySchema = z.object({
  guests: z.array(guestSchema).min(1).max(300),
});

// Bulk-add guests to a party — the host picks several contacts at once
// (device contact picker in the app, or types names in on web) and they
// all land here in one call. Each guest gets their own rsvp_token
// (default-generated by the DB) the moment the row is created, so the
// caller can immediately build that guest's RSVP link to share.
export async function POST(req: NextRequest, { params }: Params) {
  const { id } = await params;
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  const { data: party } = await supabase
    .from("parties")
    .select("id")
    .eq("id", id)
    .eq("host_id", user.id)
    .single();
  if (!party) return NextResponse.json({ error: "Not found" }, { status: 404 });

  const json = await req.json().catch(() => null);
  const parsed = bodySchema.safeParse(json);
  if (!parsed.success) {
    return NextResponse.json(
      { error: parsed.error.issues[0]?.message ?? "Invalid request" },
      { status: 400 }
    );
  }

  const rows = parsed.data.guests.map((g) => ({
    party_id: id,
    name: g.name,
    phone: g.phone ?? null,
  }));

  const { data, error } = await supabase.from("party_guests").insert(rows).select();
  if (error) return NextResponse.json({ error: error.message }, { status: 500 });

  return NextResponse.json({ guests: data }, { status: 201 });
}

export async function DELETE(req: NextRequest, { params }: Params) {
  const { id } = await params;
  const { searchParams } = new URL(req.url);
  const guestId = searchParams.get("guestId");
  if (!guestId) return NextResponse.json({ error: "guestId is required" }, { status: 400 });

  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  const { data: party } = await supabase
    .from("parties")
    .select("id")
    .eq("id", id)
    .eq("host_id", user.id)
    .single();
  if (!party) return NextResponse.json({ error: "Not found" }, { status: 404 });

  const { error } = await supabase.from("party_guests").delete().eq("id", guestId).eq("party_id", id);
  if (error) return NextResponse.json({ error: error.message }, { status: 500 });
  return NextResponse.json({ ok: true });
}
