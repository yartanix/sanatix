-- ============================================================
-- SANATIX — Migration 017
-- Discovered while scoping the Organizer mobile app's "attendee list
-- & check-in" feature (explicitly requested): bookings had no
-- check-in state at all — organizers could already read their event's
-- bookings (bookings_read_as_organizer, migration 002) but had no way
-- to mark anyone as checked in at the door. Adds the same kind of
-- check-in state migration 015/016 already added for party guests and
-- vendor inquiries, scoped to the organizer of the booking's event.
--
-- bookings.qr_code (schema.sql) is already a unique per-booking code
-- generated by create_bookings() — reused here as the entry code,
-- same no-camera-required design as the party door-pass check-in.
-- ============================================================

alter table bookings
  add column if not exists checked_in_at  timestamptz,
  add column if not exists checked_in_via text check (checked_in_via in ('organizer'));

-- Organizers may update only the check-in fields on a booking for
-- their own event — everything else on the row (amount, qr_code,
-- payment_ref, etc.) stays exactly as locked down by migration 013's
-- enforce_bookings_field_protection trigger, which already fires for
-- every non-privileged session regardless of which RLS policy let
-- the UPDATE through.
create policy "bookings_checkin_as_organizer" on bookings for update using (
  exists (
    select 1 from events
    where events.id = bookings.event_id
      and events.organizer_id = auth.uid()
  )
);

-- check_in_booking(event_id, code) resolves `code` against either the
-- full qr_code or its uppercase 8-character prefix (so door staff can
-- type a short code instead of scanning), scoped to one event so an
-- organizer can only check in bookings for events they own.
create or replace function check_in_booking(p_event_id uuid, p_code text)
returns table (booking_id uuid, guest_name text, already_checked_in boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  b record;
begin
  if not exists (select 1 from events where id = p_event_id and organizer_id = auth.uid()) then
    raise exception 'event not found';
  end if;

  select bk.id, bk.checked_in_at, pr.full_name into b
  from bookings bk
  join profiles pr on pr.id = bk.user_id
  where bk.event_id = p_event_id
    and bk.status = 'confirmed'
    and (bk.qr_code = p_code or upper(left(bk.qr_code, 8)) = upper(p_code));

  if b.id is null then
    raise exception 'no confirmed booking found for this code';
  end if;

  if b.checked_in_at is not null then
    return query select b.id, b.full_name, true;
    return;
  end if;

  update bookings set checked_in_at = now(), checked_in_via = 'organizer' where id = b.id;

  return query select b.id, b.full_name, false;
end;
$$;

grant execute on function check_in_booking(uuid, text) to authenticated;
